import mongoose from "mongoose";
// Define the user schema structure with validation and constraints
const userSchema = new mongoose.Schema(
  {
    username: {
      type: String,
      required: true,
      unique: true,
      trim: true,
    },
    email: {
      type: String,
      required: true,
      unique: true,
      trim: true,
      lowercase: true,
    },
    password: {
      type: String,
      required: true,
      select: false,
    },
    role: {
      type: String,
      enum: ["customer", "admin"],
      default: "customer",
    },
    resetPasswordToken: {
      type: String,
      default: null,
      select: false,
    },
    resetPasswordExpires: {
      type: Date,
      default: null,
      select: false,
    },
  },
  // Automatically add createdAt and updatedAt timestamps
  { timestamps: true },
);
// Create and export the User model based on the schema
const User = mongoose.model("User", userSchema);
export default User;
